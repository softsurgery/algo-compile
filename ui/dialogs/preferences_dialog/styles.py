"""
Styles and dynamic themes for PreferencesDialog.
"""

from ui.styles import DARK_THEME, LIGHT_THEME


def apply_preferences_styles(dialog, is_dark: bool):
    """Applies theme, custom tree styling, splitter styling, and card styling to PreferencesDialog."""
    dialog.setStyleSheet(DARK_THEME if is_dark else LIGHT_THEME)

    if is_dark:
        tree_bg = "#181825"
        tree_border = "#313244"
        item_fg = "#cdd6f4"
        item_hover = "rgba(205, 214, 244, 0.08)"
        sel_bg = "#313244"
        sel_fg = "#89b4fa"
        handle_bg = "#45475a"
        card_bg = "#181825"
        card_border = "#313244"
        desc_fg = "#a6adc8"
        sep_color = "#313244"
        sys_card_bg = "rgba(137, 180, 250, 0.12)"
        sys_card_border = "rgba(137, 180, 250, 0.25)"
    else:
        tree_bg = "#f8fafc"
        tree_border = "#cbd5e1"
        item_fg = "#334155"
        item_hover = "#f1f5f9"
        sel_bg = "#e0e7ff"
        sel_fg = "#1d4ed8"
        handle_bg = "#cbd5e1"
        card_bg = "#ffffff"
        card_border = "#e2e8f0"
        desc_fg = "#64748b"
        sep_color = "#e2e8f0"
        sys_card_bg = "rgba(37, 99, 235, 0.08)"
        sys_card_border = "rgba(37, 99, 235, 0.2)"

    # Style left tree view with minimal margin and NO square borders
    dialog.tree.setStyleSheet(
        f"QTreeWidget {{"
        f"  background-color: {tree_bg};"
        f"  border: 1px solid {tree_border};"
        f"  border-radius: 8px;"
        f"  padding: 4px 2px;"
        f"  outline: none;"
        f"  show-decoration-selected: 0;"
        f"}}"
        f"QTreeWidget::item {{"
        f"  padding: 6px 6px;"
        f"  margin: 1px 2px;"
        f"  border-radius: 6px;"
        f"  color: {item_fg};"
        f"  border: none;"
        f"  outline: none;"
        f"}}"
        f"QTreeWidget::item:hover {{"
        f"  background-color: {item_hover};"
        f"  border: none;"
        f"  outline: none;"
        f"}}"
        f"QTreeWidget::item:selected {{"
        f"  background-color: {sel_bg};"
        f"  color: {sel_fg};"
        f"  font-weight: bold;"
        f"  border: none;"
        f"  outline: none;"
        f"}}"
        f"QTreeWidget::item:selected:active {{"
        f"  background-color: {sel_bg};"
        f"  color: {sel_fg};"
        f"  border: none;"
        f"  outline: none;"
        f"}}"
        f"QTreeWidget::item:selected:!active {{"
        f"  background-color: {sel_bg};"
        f"  color: {sel_fg};"
        f"  border: none;"
        f"  outline: none;"
        f"}}"
        f"QTreeWidget::item:focus {{"
        f"  border: none;"
        f"  outline: none;"
        f"}}"
        f"QTreeWidget::branch {{"
        f"  background: transparent;"
        f"  border: none;"
        f"  outline: none;"
        f"}}"
        f"QTreeWidget::branch:selected {{"
        f"  background: transparent;"
        f"  border: none;"
        f"  outline: none;"
        f"}}"
    )

    # Style splitter handle
    dialog.splitter.setStyleSheet(
        f"QSplitter::handle:horizontal {{"
        f"  background-color: transparent;"
        f"  width: 6px;"
        f"}}"
        f"QSplitter::handle:horizontal:hover {{"
        f"  background-color: {handle_bg};"
        f"  border-radius: 3px;"
        f"}}"
    )

    # Style card containers, descriptions and separators inside pages
    card_style = (
        f"QFrame#pref_card {{"
        f"  background-color: {card_bg};"
        f"  border: 1px solid {card_border};"
        f"  border-radius: 8px;"
        f"}}"
        f"QGroupBox {{"
        f"  background-color: {card_bg};"
        f"  border: 1px solid {card_border};"
        f"  border-radius: 8px;"
        f"  margin-top: 12px;"
        f"  padding: 14px 14px 14px 14px;"
        f"  font-weight: bold;"
        f"}}"
        f"QGroupBox::title {{"
        f"  subcontrol-origin: margin;"
        f"  left: 14px;"
        f"  padding: 0 4px;"
        f"  color: {sel_fg};"
        f"}}"
        f"QLabel#pref_desc {{"
        f"  color: {desc_fg};"
        f"}}"
        f"QFrame#pref_separator {{"
        f"  border: none;"
        f"  background-color: {sep_color};"
        f"  height: 1px;"
        f"  max-height: 1px;"
        f"}}"
        f"QLabel#pref_sys_info {{"
        f"  background-color: {sys_card_bg};"
        f"  border: 1px solid {sys_card_border};"
        f"  border-radius: 6px;"
        f"  padding: 10px 14px;"
        f"}}"
    )
    dialog.pages.setStyleSheet(card_style)

    # Update component icons
    dialog.tree.update_icons(is_dark)
    dialog.page_theme.update_icons(is_dark)
    dialog.page_colors.update_icons(is_dark)
    dialog.action_bar.update_icons(is_dark)
